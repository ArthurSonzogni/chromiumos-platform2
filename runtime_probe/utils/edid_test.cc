// Recalculates the checksum byte (last byte of the 128-byte block) so that
// the sum of all 128 bytes in the block modulo 256 is 0.
void FixChecksum(std::vector<uint8_t>& blob, size_t block_index = 0) {
  size_t start = block_index * 128;
  size_t end = start + 128;
  if (blob.size() < end) {
    return;
  }
  uint8_t sum = 0;
  for (size_t i = start; i < end - 1; ++i) {
    sum += blob[i];
  }
  blob[end - 1] = static_cast<uint8_t>(256 - sum);
}

